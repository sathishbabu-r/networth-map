import {test,expect,afterEach,vi} from 'vitest';
import {randomBytes} from 'node:crypto';
import {readFile,stat} from 'node:fs/promises';
import {emptyMap} from '../shared/map-engine';
import {checkInContent,localDay,dailyProgressRecords} from '../shared/daily-progress.mjs';
import {financialStatus} from '../shared/financial-status';
import {dispatch} from '../local-test/runtime';
const ids:string[]=[];
const id=()=>{const value=randomBytes(32).toString('hex');ids.push(value);return value;};
const call=(account:string,name:string,args:any={})=>dispatch('server-test',account,name,args);
afterEach(async()=>{for(const account of ids.splice(0))await call(account,'test:reset');vi.restoreAllMocks();});
test('disposable accounts save, edit, isolate records, reject stale revisions and replay after restart',async()=>{
 const a=id(),b=id(),map=emptyMap();
 const content={concern:'Disposable planning',facts:[],goal:null,action:null,outcome:null,map};
 expect(await call(a,'huddles:current')).toBeNull();
 expect(await call(a,'huddles:save',{content,expectedRevision:0})).toBe(1);
 expect(await call(b,'huddles:current')).toBeNull();
 content.map.data.monthlyWants='0';
 expect(await call(a,'huddles:save',{content,expectedRevision:1})).toBe(2);
 await expect(call(a,'huddles:save',{content,expectedRevision:0})).rejects.toThrow(/changed/);
 const file='.test-data/'+a+'.json';expect((await stat(file)).mode&0o777).toBe(0o600);
 expect(JSON.parse(await readFile(file,'utf8'))).toHaveLength(2);
 vi.resetModules();const restarted=await import('../local-test/runtime');
 const saved=await restarted.dispatch('server-test',a,'huddles:current',{});
 expect(saved.revision).toBe(2);expect(saved.content.map.data.monthlyWants).toBe('0');
 expect(financialStatus(saved.content.map).inputs.monthlyWants.status).toBe('CONFIRMED_ZERO');
 expect(financialStatus(saved.content.map).metrics.networth.status).toBe('UNKNOWN');
});
test('offline intelligence runs eight specialists, verification and CFO on blank/partial data; Coach preserves unknowns',async()=>{
 const a=id(),network=vi.spyOn(globalThis,'fetch').mockRejectedValue(Error('No network allowed'));
 const map=emptyMap();map.data.monthlyWants='0';map.data.grossPersonalIncome='1200000';map.estimates=['grossPersonalIncome'];
 const content={concern:'Disposable clarity',facts:[],goal:null,action:null,outcome:null,map};
 await call(a,'huddles:save',{content,expectedRevision:0});
 const report=JSON.parse(await call(a,'intelligence:review',{intent:'Understand my financial picture',full:true}));
 expect(report.invoked).toHaveLength(8);expect(report.raw).toHaveLength(8);expect(report.verified.failed).toEqual([]);
 expect(report.test_mode).toBe('offline');expect(report.verified.state).toBe('INSUFFICIENT_DATA');
 expect(report.verified.calculations.some((x:any)=>x.key==='networth')).toBe(false);
 expect(report.cfo.story).toMatch(/incomplete/);expect(report.cfo.behaviour).toBeNull();
 expect(JSON.parse((await call(a,'intelligence:latest')).report)).toEqual(report);
 const reply=await call(a,'coach:reply',{messages:[{role:'user',content:'What is my net worth?'}]});
 expect(reply.text).toMatch(/Offline test Coach.*unavailable/);
 const proposed=await call(a,'coach:reply',{messages:[{role:'user',content:'monthly needs is unknown'}]});
 expect(proposed.proposal.map.unknowns).toContain('monthlyNeeds');expect(proposed.proposal.map.estimates).toContain('grossPersonalIncome');
 const blank=await call(id(),'coach:reply',{messages:[{role:'user',content:'Hello'}]});expect(blank.text).toMatch(/Offline test Coach/);
 expect(network).not.toHaveBeenCalled();
});
test('commitments and confirmed zero outcomes persist without modifying financial balances',async()=>{
 const a=id(),map=emptyMap();map.covered=['own','owe'];map.data.assets=[{id:'cash',description:'Test cash',category:'cash',value:'1000',purpose:'personal',annualNetIncome:'0'}];map.data.hasNoLiabilitiesConfirmed=true;
 const content={concern:'Test progress',facts:[],goal:null,action:null,outcome:null,map};
 await call(a,'huddles:save',{content,expectedRevision:0});
 const snapshot={key:'cash',label:'Test cash',kind:'exact',amount:1000,lower:null,upper:null,scope:'personal',period:'point_in_time',currency:'INR',asOf:'',note:'Test supplied cash'};
 const next=checkInContent(content,{action:'Review recurring spending',goal:'Understand my spending',useExisting:false,status:'completed',date:localDay(),change:'Reviewed costs',obstacle:'',impactType:'expense_reduction',amount:'0',confirmed:true},snapshot);
 await call(a,'huddles:save',{content:next,expectedRevision:1});
 const saved=await call(a,'huddles:current'),history=await call(a,'huddles:history',{paginationOpts:{numItems:50,cursor:null},latestFirst:true});
 expect(saved.content.map).toEqual(map);expect(saved.content.action.text).toBe('Review recurring spending');
 expect(saved.content.outcome.amount).toBe(0);expect(dailyProgressRecords(history.page,saved)).toHaveLength(1);
 await expect(call(a,'intelligence:record',{userId:'production-user',revision:2,report:'private'})).rejects.toThrow(/unavailable/);
});
